import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

async function readTextFiles(dir, extensions) {
  const absoluteDir = path.join(repoRoot, dir);
  const entries = await readdir(absoluteDir, { withFileTypes: true });
  const files = entries
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name)
    .filter((name) => extensions.includes(path.extname(name)));

  const map = {};
  await Promise.all(
    files.map(async (file) => {
      const slug = path.basename(file, path.extname(file));
      const absolutePath = path.join(absoluteDir, file);
      map[slug] = await readFile(absolutePath, "utf8");
    }),
  );

  return map;
}

async function main() {
  const projects = await readTextFiles("content/projects", [".mdx"]);
  const articles = await readTextFiles("content/articles", [".md"]);

  const logoPath = path.join(repoRoot, "public", "design", "kemma-original.png");
  const logoBase64 = await readFile(logoPath, "base64");

  const generated = `// This file is generated by scripts/generate-content-manifest.mjs. Do not edit by hand.
// Bundled content is required for Cloudflare Workers (no runtime filesystem access).

export const PROJECT_MDX_BY_SLUG = ${JSON.stringify(projects, null, 2)} as const;
export type ProjectSlug = keyof typeof PROJECT_MDX_BY_SLUG;

export const ARTICLE_MD_BY_SLUG = ${JSON.stringify(articles, null, 2)} as const;
export type ArticleSlug = keyof typeof ARTICLE_MD_BY_SLUG;

export const PUBLIC_BASE64_BY_PATH = ${JSON.stringify({ "design/kemma-original.png": logoBase64 }, null, 2)} as const;
`;

  const outPath = path.join(repoRoot, "lib", "generated", "content-manifest.ts");
  const outDir = path.dirname(outPath);
  await mkdir(outDir, { recursive: true });
  await writeFile(outPath, generated);
}

await main();

